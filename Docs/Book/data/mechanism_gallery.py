"""Render a gallery using the fork's native, manually controlled mechanism API."""

import argparse
import html
import json
from pathlib import Path
import re

from rdkit.Chem.Draw import rdMolDraw2D

from mechanism_common import Scene, electron_arrow, positioned_molecule, render_scene
from rdkit.Geometry import Point2D


def radical_scene():
  anchor = rdMolDraw2D.MechanismAnchor
  head = rdMolDraw2D.ElectronArrowHead
  chlorine = positioned_molecule("ClCl", [(0, 0), (1.5, 0)])
  arrows = [
    electron_arrow(
      anchor.Bond(0, 0, offset=Point2D(0, 0.12)), anchor.Atom(0, 0),
      (0.7, 0.8), (-0.35, 0.7), head.FishhookLeft),
    electron_arrow(
      anchor.Bond(0, 0, offset=Point2D(0, -0.12)), anchor.Atom(0, 1),
      (0.8, -0.8), (1.85, -0.7), head.FishhookRight),
  ]
  return Scene(
    "homolysis", "Single-electron movement: chlorine homolysis",
    "Each fishhook transfers one electron from the Cl-Cl bond to a different "
    "chlorine atom. The supplied reactant graph retains its bond; radicals "
    "are not generated by the drawing API.",
    [chlorine], arrows, width=360, height=230)


def build_scenes():
  if not hasattr(rdMolDraw2D.MolDraw2DSVG, "DrawMechanism"):
    raise RuntimeError(
      "This gallery requires the RDKit fork with DrawMechanism, not stock RDKit.")
  from mechanism_concerted import scenes as concerted_scenes
  from mechanism_carbonyl import scenes as carbonyl_scenes
  return [*concerted_scenes(), *carbonyl_scenes(), radical_scene()]


def gallery_html(entries):
  cards = []
  for entry in entries:
    title = html.escape(entry["title"])
    description = html.escape(entry["description"])
    image = html.escape(entry["files"]["svg"], quote=True)
    links = " | ".join(
      f'<a href="{html.escape(filename, quote=True)}">{kind.upper()}</a>'
      for kind, filename in entry["files"].items())
    cards.append(
      f'<article id="{entry["slug"]}"><h2>{title}</h2>'
      f'<img src="{image}" width="{entry["width"]}" height="{entry["height"]}" '
      f'alt="{title}: {description}"><p>{description}</p>'
      f'<p class="details">{entry["arrows"]} electron-flow arrows; '
      f'{entry["fragments"]} explicitly supplied fragments. {links}</p></article>')
  return """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Native RDKit mechanism gallery</title>
<style>
body { margin: 0 auto; padding: 2rem; max-width: 100rem; font: 17px/1.5 system-ui, sans-serif;
       color: #18202c; background: #f4f6f8; }
header { max-width: 70rem; margin-bottom: 2rem; }
main { display: grid; grid-template-columns: repeat(auto-fit, minmax(min(100%, 40rem), 1fr));
       gap: 1.5rem; }
article { background: white; padding: 1.5rem; border: 1px solid #d6dce3; border-radius: .5rem; }
h1 { margin-bottom: .5rem; } h2 { font-size: 1.2rem; margin-top: 0; }
img { display: block; max-width: 100%; height: auto; margin: 0 auto; }
.details { font-size: .85rem; color: #48576b; }
a { color: #153e8c; } code { font-size: .95em; }
</style></head><body><header>
<h1>Native RDKit mechanism gallery</h1>
<p>Molecules, lone pairs, curves, and arrowheads are rendered together by
<code>DrawMechanism</code>. These are native SVG drawings, not SVG overlays.</p>
<p>Every structure, electron-flow endpoint, and curve is explicitly authored.
The API does not predict mechanisms, generate products, or route around obstacles.
The carbonyl panels illustrate consecutive steps; the resonance panel illustrates
electron bookkeeping, not a chemical reaction.</p>
</header><main>""" + "\n".join(cards) + "</main></body></html>\n"


def generate_gallery(scenes, output, *, png=False):
  """Write native figures, an offline HTML index, and a machine-readable manifest."""
  if not scenes:
    raise ValueError("Select at least one gallery scene")
  slugs = [scene.slug for scene in scenes]
  if len(set(slugs)) != len(slugs) or any(
      re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug) is None for slug in slugs):
    raise ValueError("Scene slugs must be unique, lowercase, hyphenated identifiers")
  if png and not hasattr(rdMolDraw2D, "MolDraw2DCairo"):
    raise RuntimeError("--png requires RDKit built with Cairo support")

  artifacts = {}
  entries = []
  for scene in scenes:
    svg, positions = render_scene(scene)
    files = {"svg": f"{scene.slug}.svg"}
    artifacts[files["svg"]] = svg.encode("utf-8")
    if png:
      image, _ = render_scene(scene, "png")
      files["png"] = f"{scene.slug}.png"
      artifacts[files["png"]] = image
    entries.append({
      "slug": scene.slug, "title": scene.title, "description": scene.description,
      "width": scene.width, "height": scene.height,
      "arrows": len(scene.arrows), "fragments": len(scene.mols),
      "originalAtoms": [len(fragment) for fragment in positions], "files": files,
    })
  manifest = {"schemaVersion": 1, "renderer": "RDKit DrawMechanism", "scenes": entries}
  artifacts["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
  artifacts["index.html"] = gallery_html(entries).encode("utf-8")
  output = Path(output)
  output.mkdir(parents=True, exist_ok=True)
  for name, data in artifacts.items():
    (output / name).write_bytes(data)
  return manifest


def main(argv=None):
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--output", type=Path, default=Path("mechanism-gallery"),
                      help="Output directory (default: mechanism-gallery)")
  parser.add_argument("--png", action="store_true",
                      help="Also render native Cairo PNGs; requires Cairo support")
  parser.add_argument("--only", action="append", metavar="SLUG",
                      help="Render only this scene; repeat to select several")
  parser.add_argument("--list", action="store_true", help="List scene identifiers and exit")
  args = parser.parse_args(argv)
  try:
    scenes = build_scenes()
    if args.only:
      unknown = set(args.only) - {scene.slug for scene in scenes}
      if unknown:
        parser.error(f"Unknown scenes: {', '.join(sorted(unknown))}")
      scenes = [scene for scene in scenes if scene.slug in args.only]
    if args.list:
      for scene in scenes:
        print(f"{scene.slug}: {scene.title}")
      return 0
    manifest = generate_gallery(scenes, args.output, png=args.png)
  except (OSError, ValueError, RuntimeError) as error:
    parser.exit(1, f"Mechanism gallery: {error}\n")
  print(f"Rendered {len(manifest['scenes'])} scenes: {(args.output / 'index.html').resolve()}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
